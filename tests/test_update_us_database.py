"""使用独立临时 schema 验证事务和回滚；不修改业务表。

HSCODE_TEST_US_JSON=/path/to/official.json uv run python -m unittest discover -s tests -v
"""
import os
from pathlib import Path
import tempfile
import unittest
import uuid

import psycopg
from psycopg import sql
from psycopg.conninfo import make_conninfo

from hscode.config import DEFAULT_DSN
from scripts.update_us import COL_SQL, update, restore


@unittest.skipUnless(os.environ.get('HSCODE_TEST_US_JSON'), '需要官方 JSON 测试文件')
class DatabaseUpdateTests(unittest.TestCase):
    def test_update_idempotence_failure_rollback_and_restore(self):
        schema = 'test_hts_' + uuid.uuid4().hex
        base = DEFAULT_DSN
        dsn = make_conninfo(base, options=f'-c search_path={schema},public')
        raw = Path(os.environ['HSCODE_TEST_US_JSON']).read_bytes()
        with psycopg.connect(base, autocommit=True) as admin:
            admin.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
            try:
                with psycopg.connect(dsn) as c:
                    c.execute('CREATE TABLE hs_code (LIKE public.hs_code INCLUDING DEFAULTS INCLUDING GENERATED)')
                    c.execute(f'INSERT INTO hs_code ({COL_SQL}) SELECT {COL_SQL} FROM public.hs_code')
                    c.execute('CREATE TABLE hs_chapter AS SELECT * FROM public.hs_chapter')
                    c.execute('CREATE TABLE data_release AS SELECT * FROM public.data_release')
                    c.execute('ALTER TABLE data_release ALTER COLUMN id SET NOT NULL')
                    c.execute('ALTER TABLE data_release ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100)')
                    c.execute('ALTER TABLE data_release ALTER COLUMN imported_at SET DEFAULT now()')
                    # 固定旧版基线，使测试不依赖业务库当前已更新到哪个版本。
                    c.execute("UPDATE data_release SET release='2026 Rev 19' WHERE country='US'")
                    c.execute("DELETE FROM hs_code WHERE country='US' AND code='99030470'")
                def fingerprint(country):
                    with psycopg.connect(dsn) as c:
                        return c.execute("SELECT md5(string_agg(row_to_json(t)::text, '' ORDER BY code)) "
                                         'FROM hs_code t WHERE country=%s', (country,)).fetchone()[0]
                before_cn = fingerprint('CN')
                before_us = fingerprint('US')
                with tempfile.TemporaryDirectory() as work:
                    directory = Path(work)
                    preview = update(dsn, '2026 Rev 21', raw, apply=False, directory=directory)
                    self.assertFalse(preview['applied'])
                    self.assertEqual(fingerprint('US'), before_us)
                    with psycopg.connect(dsn) as c:
                        c.execute("CREATE FUNCTION reject_update() RETURNS trigger LANGUAGE plpgsql AS $$ "
                                  "BEGIN RAISE EXCEPTION 'test failure'; END $$")
                        c.execute('CREATE TRIGGER reject_update BEFORE INSERT ON hs_code '
                                  'FOR EACH STATEMENT EXECUTE FUNCTION reject_update()')
                    with self.assertRaises(psycopg.Error):
                        update(dsn, '2026 Rev 21', raw, apply=True, directory=directory)
                    self.assertEqual(fingerprint('US'), before_us)
                    with psycopg.connect(dsn) as c:
                        c.execute('DROP TRIGGER reject_update ON hs_code')
                    applied = update(dsn, '2026 Rev 21', raw, apply=True, directory=directory)
                    self.assertTrue(applied['applied'])
                    self.assertEqual(fingerprint('CN'), before_cn)
                    again = update(dsn, '2026 Rev 21', raw, apply=True, directory=directory)
                    self.assertFalse(again['applied'])
                    self.assertEqual(again['changed'], 0)
                    with self.assertRaises(ValueError):
                        update(dsn, '2025 Rev 1', raw, apply=True, directory=directory)
                    restore(dsn, Path(applied['backup']))
                    self.assertEqual(fingerprint('US'), before_us)
                    self.assertEqual(fingerprint('CN'), before_cn)
            finally:
                admin.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(schema)))
